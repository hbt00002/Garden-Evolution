// One <rect> per run of same-coloured pixels in a row: a few dozen elements an icon.
function draw(rows) {
  const rects = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      const ch = row[x];
      if (ch === ".") { x++; continue; }
      let end = x;
      while (row[end + 1] === ch) end++;
      rects.push(`<rect x="${x}" y="${y}" width="${end - x + 1}" height="1"${ch === "+" ? ' opacity=".5"' : ""}/>`);
      x = end + 1;
    }
  });
  return rects.join("");
}

export const PIXEL_ICONS = Object.keys(ICONS);

// The icon as an SVG string, sized by CSS (it scales with crisp pixels).
export function pixelIcon(name, className = "pixel-icon") {
  const rows = ICONS[name];
  if (!rows) return "";
  const width = Math.max(...rows.map(row => row.length));
  return `<svg class="${className}" data-icon="${name}" viewBox="0 0 ${width} ${rows.length}" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${draw(rows)}</svg>`;
}
